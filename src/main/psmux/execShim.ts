// Claude Code 2.1.329+ 팀원 칸 명령 `/bin/sh -c "cd … && exec env NAME=VALUE … 프로그램 인자"` 대응.
// psmux는 /bin/sh -c 껍질을 벗겨 PowerShell에서 실행하는데 PowerShell에는 exec가 없어 칸이 바로 죽는다(psmux의 env 처리는 줄이 env로
// 시작할 때만 붙음). 앱 세션 PATH(세션 환경) 맨 앞에 exec.ps1을 두어 그 줄이 그대로 돌게 한다. 순수 로직 + 파일 쓰기.

import { execFile } from 'node:child_process';
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, win32 } from 'node:path';

import { log } from '../logger';

/** 셸이 찾을 이름(PATH에서 exec → exec.ps1). */
export const EXEC_SHIM_NAME = 'exec.ps1';
/** shim 전용 폴더(<앱 데이터> 아래). PATH 맨 앞에 오므로 다른 파일을 두지 않는다. */
export const EXEC_SHIM_DIR = 'exec-shim';

/**
 * exec.ps1 내용(ASCII만: Windows PowerShell 5.1은 BOM 없는 파일을 ANSI로 읽음).
 * 인자는 PowerShell이 넘긴 그대로 쓴다: 이전 `cd … && env …` 형태(psmux가 처리, 실제 팀원이 뜨던 경로)도 \X를 풀지 않고 그대로
 * 넘긴다(실측: 같은 인자로 두 형태의 argv가 같음). #! 줄·.js 실행은 넣지 않는다(팀원 명령의 프로그램은 claude.exe 또는 node.exe 경로).
 * 실행하지 못한 프로그램(없는 명령 등)은 127로 끝낸다(POSIX 셸과 같게, 0으로 성공처럼 보이지 않게).
 * shortcut: 스크립트 인자는 PowerShell이 해석하므로 맨몸 `--`·`-이름:값`·따옴표 없는 쉼표 목록은 바뀔 수 있다(지금 팀원 명령에는 그런 모양이
 * 없음). 그런 플래그가 생기면 인자를 그대로 넘기는 네이티브 실행 파일로 바꾼다.
 */
export const EXEC_SHIM = [
  '# Rich psmux: POSIX `exec [env] [NAME=VALUE ...] program [args]` for Claude Code teammate panes in psmux.',
  '# psmux runs the pane line in PowerShell, which has no `exec`. Generated by the app; edits are overwritten.',
  '# shortcut: PowerShell parses script arguments, so a bare `--`, `-name:value` or an unquoted comma list can change.',
  '# Teammate commands have no such argument today; if one appears, replace this script with a native launcher.',
  '$a = @($args)',
  "if ($a.Count -gt 0 -and $a[0] -eq 'env') { $a = @($a | Select-Object -Skip 1) }",
  '$i = 0',
  "while ($i -lt $a.Count -and $a[$i] -match '^([A-Za-z_]\\w*)=(.*)$') { [Environment]::SetEnvironmentVariable($Matches[1], $Matches[2], 'Process'); $i++ }",
  'if ($i -ge $a.Count) { exit 0 }',
  '$rest = @(); if ($i + 1 -lt $a.Count) { $rest = @($a[($i + 1)..($a.Count - 1)]) }',
  '$global:LASTEXITCODE = 0',
  '& $a[$i] @rest',
  'if (-not $? -and $LASTEXITCODE -eq 0) { exit 127 }',
  'exit $LASTEXITCODE',
  '',
].join('\r\n');

let warnedExtra = false;

/**
 * <앱 데이터>/exec-shim/exec.ps1을 쓴다(없거나 내용이 다르면 다시 씀). 폴더에 다른 파일이 있으면 이름만 한 번 경고한다
 * (PATH 맨 앞 폴더라 다른 실행 파일이 명령을 가로챌 수 있음).
 *
 * Returns:
 *   shim 폴더.
 *
 * Raises:
 *   Error: 폴더를 만들거나 파일을 쓰지 못했을 때.
 */
export function ensureExecShim(dataDir: string): string {
  const dir = join(dataDir, EXEC_SHIM_DIR);
  const file = join(dir, EXEC_SHIM_NAME);
  let cur: string | null = null;
  try {
    cur = readFileSync(file, 'utf8');
  } catch { /* 처음 또는 지워짐 */ }
  if (cur !== EXEC_SHIM) {
    mkdirSync(dir, { recursive: true });
    writeFileSync(file, EXEC_SHIM, 'utf8');
  }
  const extra = readdirSync(dir).filter((n) => n.toLowerCase() !== EXEC_SHIM_NAME);
  if (extra.length && !warnedExtra) {
    warnedExtra = true;
    log('warn', `exec shim folder has other files (first on app sessions' PATH): ${extra.slice(0, 10).join(', ')}`);
  }
  return dir;
}

/** 환경 블록의 PATH(Windows는 이름 대소문자 무시: Path·PATH). 이름은 원래 표기 그대로 돌려준다. 없거나 비면 null. */
export function envPath(env: NodeJS.ProcessEnv): { key: string; value: string } | null {
  const key = Object.keys(env).find((k) => k.toUpperCase() === 'PATH');
  const value = key ? env[key] : undefined;
  return key && value && value.trim() ? { key, value } : null;
}

const normDir = (p: string): string => win32.normalize(p.trim().replace(/^"(.*)"$/, '$1')).replace(/[\\/]+$/, '').toLowerCase();

/**
 * 앱 세션 칸의 PATH: shim 폴더를 맨 앞에 두고 나머지는 base 그대로(순서·빈 항목 유지, 같은 폴더가 이미 있으면 그 항목만 뺌).
 * base는 앱이 세션을 만들 때 psmux에 넘기는 환경의 PATH다(앱 세션 칸은 이 PATH로 뜬다, 실측). shim 말고 남는 실제 항목이 없으면
 * null(PATH를 shim만 남겨 칸의 모든 명령이 깨지는 일을 막기 위해 설정하지 않음).
 */
export function sessionPath(shimDir: string, base: string | null | undefined): string | null {
  if (!base || !shimDir.trim()) return null;
  const me = normDir(shimDir);
  const rest = base.split(';').filter((p) => p.trim() === '' || normDir(p) !== me);
  if (!rest.some((p) => p.trim() !== '')) return null;
  return [shimDir, ...rest].join(';');
}

/** Windows PowerShell 5.1(powershell.exe)인지: 팀원 명령의 `&&`를 해석하지 못해 PowerShell 7이 필요하다. */
export function isWindowsPowerShell(shell: string): boolean {
  return /(^|[\\/])powershell(\.exe)?$/i.test(shell.trim());
}

/** PowerShell 실행 정책이 로컬 .ps1을 막는지(Restricted·AllSigned). */
export function policyBlocksShim(policy: string): boolean {
  return /^(Restricted|AllSigned)$/i.test(policy.trim());
}

/**
 * 셸의 실효 실행 정책(Get-ExecutionPolicy). PowerShell이 아니거나 확인하지 못하면 null.
 *
 * Args:
 *   shell: 칸 셸 실행 파일(설정의 pwsh 경로 또는 psmux default-shell).
 *   env: 실행 환경(호출부의 정리된 환경).
 */
export function readExecutionPolicy(shell: string, env: NodeJS.ProcessEnv): Promise<string | null> {
  if (!/(^|[\\/])(pwsh|powershell)(\.exe)?$/i.test(shell.trim())) return Promise.resolve(null);
  return new Promise((resolve) => {
    execFile(shell.trim(), ['-NoProfile', '-NonInteractive', '-Command', 'Get-ExecutionPolicy'], { encoding: 'utf8', windowsHide: true, timeout: 15000, env },
      (err, stdout) => resolve(err ? null : (stdout ?? '').trim().split(/\r?\n/).pop()?.trim() || null));
  });
}
